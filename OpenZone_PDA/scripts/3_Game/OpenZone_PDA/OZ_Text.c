// Обрізання рядка по БАЙТАХ без розрізання символу навпіл.
//
// string.Length() і Substring() в Enforce байтові, а текст у полях -- UTF-8:
// кирилична літера займає два байти, і сліпий Substring(0, max) інколи
// лишає від неї перший байт без другого. Такий хвіст не прочитає жоден
// декодер -- Discord малює замість нього U+FFFD. Зміряно на
// «Схрон біля Доброго»: 33 байти різались у 32 між літерами лише випадково.
// РІЖЕ ОДИН РІЗАК НА ВСЮ СЕРІЮ -- ядерний OZ_Rpc.CutSafe.
//
// Тут стояла друга копія того самого циклу «відступити до початку символу»,
// і правку крайового випадку в одній із них довелось би вносити в обидві.
// Клас лишається входом, а не зникає: у CutSafe інший договір -- він бере
// АБСОЛЮТНІ межі вікна й нічого не знає про «а якщо рядок і так короткий».
// Саме ця перевірка тут і живе; без неї Substring читав би за кінцем.
class OZ_Text
{
    static string Clip(string s, int maxBytes)
    {
        if (maxBytes <= 0)
            return "";
        if (s.Length() <= maxBytes)
            return s;

        return s.Substring(0, OZ_Rpc.CutSafe(s, 0, maxBytes));
    }
}
